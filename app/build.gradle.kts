// Release signing: the keystore and its passwords live OUTSIDE the repository.
// Default location: <user home>/.casacheck/signing.properties with keys
// storeFile, storePassword, keyAlias, keyPassword. Override with the
// environment variable CASACHECK_SIGNING_PROPERTIES.
val signingPropsFile = file(
    System.getenv("CASACHECK_SIGNING_PROPERTIES")
        ?: "${System.getProperty("user.home")}/.casacheck/signing.properties"
)
val signingProps = Properties().apply {
    if (signingPropsFile.exists()) signingPropsFile.inputStream().use { load(it) }
}

