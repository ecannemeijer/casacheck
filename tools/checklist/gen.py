#!/usr/bin/env python3
"""Generates checklist string resources (nl default, en, it) and CheckpointLibrary.kt.
Usage: python3 tools/checklist/gen.py   (from repo root or this dir)"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import common
import part1, part2, part3, part4, part5, part6, part7, part8  # noqa: F401  (register items)

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
KT = os.path.join(ROOT, "app", "src", "main", "java", "nl", "ecannemeijer", "casacheck", "domain", "checklist", "CheckpointLibrary.kt")
LANGS = [("nl", "values"), ("en", "values-en"), ("it", "values-it")]
FIELD_NAMES = dict(t="title", e="explanation", s="steps", f="lookFor", n="normal", a="abnormal", c="causes", q="consequences", r="repair", w="warning", x="expert")

def esc(s):
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s

def check_items():
    codes = set()
    for it in common.ITEMS:
        assert it["code"] not in codes, it["code"]
        codes.add(it["code"])
        for lang, _ in LANGS:
            tup = it[lang]
            assert tup[0].strip(), (it["code"], lang, "title")
            for i in range(9):
                assert tup[i].strip(), (it["code"], lang, common.FIELDS[i])
            # warning/expert must be consistently present across languages
        for i in (9, 10):
            present = [bool(it[l][i].strip()) for l, _ in LANGS]
            assert all(present) or not any(present), (it["code"], common.FIELDS[i], present)

def gen_xml():
    for lang, folder in LANGS:
        out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- GENERATED by tools/checklist/gen.py - do not edit by hand -->", "<resources>"]
        for code, nl, en, itn in common.CATEGORIES:
            name = {"nl": nl, "en": en, "it": itn}[lang]
            out.append(f'    <string name="cat_{code.lower()}">{esc(name)}</string>')
        for key, names in common.TOOLS.items():
            name = names[{"nl": 0, "en": 1, "it": 2}[lang]]
            out.append(f'    <string name="tool_{key}">{esc(name)}</string>')
        for it in common.ITEMS:
            for i, f in enumerate(common.FIELDS):
                val = it[lang][i].strip()
                if val:
                    out.append(f'    <string name="cp_{it["code"]}_{f}">{esc(val)}</string>')
        out.append("</resources>")
        d = os.path.join(RES, folder)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "checklist_strings.xml"), "w", encoding="utf-8") as fh:
            fh.write("\n".join(out) + "\n")

def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

def klist(xs):
    return "emptyList()" if not xs else "listOf(" + ", ".join(kstr(x) for x in xs) + ")"

def gen_kt():
    lines = ["// GENERATED by tools/checklist/gen.py - do not edit by hand",
             "package nl.ecannemeijer.casacheck.domain.checklist", "",
             "import nl.ecannemeijer.casacheck.R", "",
             "@Suppress(\"LargeClass\")",
             "object CheckpointLibrary {",
             "    val categories: List<CategoryDef> = listOf("]
    for idx, (code, *_rest) in enumerate(common.CATEGORIES):
        lines.append(f"        CategoryDef({kstr(code)}, R.string.cat_{code.lower()}, {idx}),")
    lines.append("    )")
    lines.append("")
    lines.append("    val tools: Map<String, Int> = mapOf(")
    for key in common.TOOLS:
        lines.append(f"        {kstr(key)} to R.string.tool_{key},")
    lines.append("    )")
    lines.append("")
    chunks = [common.ITEMS[i:i + 25] for i in range(0, len(common.ITEMS), 25)]
    lines.append("    val all: List<CheckpointDef> by lazy { " + " + ".join(f"chunk{i}()" for i in range(len(chunks))) + " }")
    lines.append("    val byCode: Map<String, CheckpointDef> by lazy { all.associateBy { it.code } }")
    lines.append("")
    for ci, chunk in enumerate(chunks):
        lines.append(f"    private fun chunk{ci}(): List<CheckpointDef> = listOf(")
        for order, it in enumerate(chunk):
            refs = []
            for f in common.FIELDS:
                refs.append(f"R.string.cp_{it['code']}_{f}" if it["nl"][common.FIELDS.index(f)].strip() else "0")
            cost = it["cost"]
            cmin, cmax = (cost if cost else (0, 0))
            ill = f"R.drawable.ill_{it['ill']}" if it["ill"] else "0"
            lines.append(
                f"        CheckpointDef(code = {kstr(it['code'])}, category = {kstr(it['cat'])}, order = {ci * 25 + order}, quick = {str(it['quick']).lower()},\n"
                f"            title = {refs[0]}, explanation = {refs[1]}, steps = {refs[2]}, lookFor = {refs[3]}, normal = {refs[4]}, abnormal = {refs[5]},\n"
                f"            causes = {refs[6]}, consequences = {refs[7]}, repair = {refs[8]}, warning = {refs[9]}, expert = {refs[10]},\n"
                f"            costMinEur = {cmin}, costMaxEur = {cmax}, tools = {klist(it['tools'])}, illustration = {ill},\n"
                f"            conditions = {klist(it['cond'])}, roomTypes = {klist(it['rooms'])}, flags = {kstr(it['flags'])}),")
        lines.append("    )")
    lines.append("}")
    os.makedirs(os.path.dirname(KT), exist_ok=True)
    with open(KT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

if __name__ == "__main__":
    check_items()
    gen_xml()
    gen_kt()
    print(f"{len(common.ITEMS)} checkpoints, {len(common.CATEGORIES)} categories written")
