#!/usr/bin/env python3
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from docs import DOCS; from questions import Q; from env import ENV; from prefs import PREFS
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RES = os.path.join(ROOT, "app/src/main/res")
KT = os.path.join(ROOT, "app/src/main/java/nl/ecannemeijer/casacheck/domain/content/ContentLibrary.kt")
LI = {"nl": 0, "en": 1, "it": 2}
def esc(s):
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'").replace('"', '\\"')
    return ("\\" + s) if s[:1] in "@?" else s
def kq(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'
for lang, folder in (("nl", "values"), ("en", "values-en"), ("it", "values-it")):
    o = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- GENERATED by tools/content/gen_content.py -->", "<resources>"]
    for d in DOCS:
        t = d[lang]
        for k, v in zip(("name", "why", "check", "who"), t):
            o.append(f'    <string name="doc_{d["code"].lower()}_{k}">{esc(v)}</string>')
        o.append(f'    <string name="doc_{d["code"].lower()}_q">{esc(d["q_" + lang])}</string>')
    for code, *texts in Q:
        o.append(f'    <string name="aq_{code}">{esc(texts[LI[lang]])}</string>')
    for code, _q, names in ENV:
        o.append(f'    <string name="env_{code}">{esc(names[LI[lang]])}</string>')
    for code, _k, names in PREFS:
        o.append(f'    <string name="pref_{code}">{esc(names[LI[lang]])}</string>')
    o.append("</resources>")
    with open(os.path.join(RES, folder, "content_strings.xml"), "w", encoding="utf-8") as f: f.write("\n".join(o) + "\n")
L = ["// GENERATED by tools/content/gen_content.py - do not edit by hand", "package nl.ecannemeijer.casacheck.domain.content", "", "import nl.ecannemeijer.casacheck.R", "",
     "object ContentLibrary {", "    val documents: List<DocumentDef> = listOf("]
for d in DOCS:
    c = d["code"].lower()
    L.append(f'        DocumentDef({kq(d["code"])}, {kq(d["it_name"])}, R.string.doc_{c}_name, R.string.doc_{c}_why, R.string.doc_{c}_check, R.string.doc_{c}_who, {kq(d["q_it"])}, R.string.doc_{c}_q),')
L += ["    )", "", "    /** Built-in agent questions; Italian text is kept verbatim so it is always available in Italian. */", "    val agentQuestions: List<AgentQuestionDef> = listOf("]
for code, nl, en, it in Q:
    L.append(f'        AgentQuestionDef({kq(code)}, R.string.aq_{code}, {kq(it)}),')
L += ["    )", "", "    val environment: List<EnvItemDef> = listOf("]
for code, q, _n in ENV:
    L.append(f'        EnvItemDef({kq(code)}, R.string.env_{code}, {kq(q) if q else "null"}),')
L += ["    )", "", "    val preferences: List<PreferenceDef> = listOf("]
for code, kind, _n in PREFS:
    L.append(f'        PreferenceDef({kq(code)}, PreferenceKind.{kind}, R.string.pref_{code}),')
L += ["    )", "}"]
os.makedirs(os.path.dirname(KT), exist_ok=True)
with open(KT, "w", encoding="utf-8") as f: f.write("\n".join(L) + "\n")
print(len(DOCS), "docs", len(Q), "questions", len(ENV), "env", len(PREFS), "prefs")
