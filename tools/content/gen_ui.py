#!/usr/bin/env python3
import os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import ui_strings, ui_strings2
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RES = os.path.join(ROOT, "app/src/main/res")
def esc(s):
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    return ("\\" + s) if s[:1] in "@?" else s
allS = ui_strings.S + ui_strings2.S
keys = [k for k, *_ in allS]
dups = {k for k in keys if keys.count(k) > 1}
assert not dups, dups
for idx, folder in ((1, "values"), (2, "values-en"), (3, "values-it")):
    o = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- GENERATED by tools/content/gen_ui.py -->", "<resources>"]
    for t in allS:
        k = t[0]; v = t[idx]
        fmt = ' formatted="false"' if ("%" in v and not re.search(r"%(\d\$)?[sd]", v)) else ""
        extra = ' translatable="false"' if k == "app_name" and idx == 1 else ""
        if k == "app_name" and idx != 1: continue
        o.append(f'    <string name="{k}"{fmt}{extra}>{esc(v)}</string>')
    o.append("</resources>")
    with open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8") as f: f.write("\n".join(o) + "\n")
print(len(allS), "strings")
